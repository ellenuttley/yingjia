"""Draws the widget's button icons and writes them to src/yingjia/icons.py.

Icons are stored as base64 PNGs inside the code, so they work offline, need
no image files next to the exe, and render the same on Windows 7 to 11
(emoji symbols don't). Run with: python tools/make_icons.py  (needs Pillow)
"""
import base64
import io
import math
import os

from PIL import Image, ImageDraw

SCALE = 4  # draw big, then shrink for smooth edges

COLOURS = {
    # (small icon colour, pick-button icon colour) per theme
    "light": ("#1c1c1c", "#ffffff"),
    "dark": ("#ffffff", "#000000"),
}


def canvas(size):
    img = Image.new("RGBA", (size * SCALE, size * SCALE), (0, 0, 0, 0))
    return img, ImageDraw.Draw(img), size * SCALE


def finish(img, size):
    out = img.resize((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    out.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def dice(colour, size=30):
    img, d, s = canvas(size)
    m, w = s * 0.08, s * 0.07
    d.rounded_rectangle([m, m, s - m, s - m], radius=s * 0.2, outline=colour, width=int(w))
    r = s * 0.075
    for fx, fy in ((0.3, 0.3), (0.7, 0.3), (0.5, 0.5), (0.3, 0.7), (0.7, 0.7)):
        cx, cy = fx * s, fy * s
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=colour)
    return finish(img, size)


def gear(colour, size=20):
    img, d, s = canvas(size)
    c, outer, inner, hole = s / 2, s * 0.46, s * 0.33, s * 0.13
    pts = []
    teeth = 8
    for i in range(teeth * 4):
        a = 2 * math.pi * i / (teeth * 4)
        r = outer if (i % 4) in (1, 2) else inner
        pts.append((c + r * math.cos(a), c + r * math.sin(a)))
    d.polygon(pts, fill=colour)
    d.ellipse([c - hole, c - hole, c + hole, c + hole], fill=(0, 0, 0, 0))
    return finish(img, size)


def lock(colour, size=20, open_=False):
    img, d, s = canvas(size)
    w = int(s * 0.1)
    body = [s * 0.18, s * 0.45, s * 0.82, s * 0.92]
    d.rounded_rectangle(body, radius=s * 0.08, fill=colour)
    left, right = s * 0.3, s * 0.7
    top = s * 0.08
    shift = s * 0.22 if open_ else 0
    d.arc([left + shift, top, right + shift, s * 0.62], 180, 360, fill=colour, width=w)
    d.line([right + shift - w / 2, s * 0.35, right + shift - w / 2, s * 0.47], fill=colour, width=w)
    if not open_:
        d.line([left + w / 2, s * 0.35, left + w / 2, s * 0.47], fill=colour, width=w)
    return finish(img, size)


def close(colour, size=20):
    img, d, s = canvas(size)
    m, w = s * 0.24, int(s * 0.11)
    d.line([m, m, s - m, s - m], fill=colour, width=w)
    d.line([m, s - m, s - m, m], fill=colour, width=w)
    return finish(img, size)


def main():
    lines = ['"""Button icons as base64 PNGs. Generated by tools/make_icons.py; do not edit."""', "",
             "ICONS = {"]
    for theme, (small, pick) in COLOURS.items():
        lines.append(f'    "{theme}": {{')
        for name, data in (("pick", dice(pick)), ("gear", gear(small)), ("lock", lock(small)),
                           ("unlock", lock(small, open_=True)), ("close", close(small))):
            lines.append(f'        "{name}": "{data}",')
        lines.append("    },")
    lines.append("}")
    path = os.path.join(os.path.dirname(__file__), "..", "src", "yingjia", "icons.py")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
